use std::{
    fs,
    io::Write,
    path::{Path, PathBuf},
    process::{Command, Stdio},
};

use anyhow::{Context, Result, bail, ensure};
use clap::{Parser, Subcommand};
use pulse_core::{Config, config::KV_BINDING};

/// Pinned so builds don't shift under us; bump deliberately.
const COMPATIBILITY_DATE: &str = "2026-10-01";
const CRON: &str = "*/10 * * * *";
const WORKER_DIR: &str = "crates/worker";

#[derive(Parser)]
#[command(name = "pulse", about = "Tooling for the github_pulse Worker")]
struct Cli {
    /// Path to the config file.
    #[arg(long, global = true, default_value = "config.toml")]
    config: PathBuf,
    #[command(subcommand)]
    command: Cmd,
}

#[derive(Subcommand)]
enum Cmd {
    /// Generate wrangler.toml and .dev.vars from the config.
    Sync {
        /// Also upload [secrets] to Cloudflare with `wrangler secret bulk`.
        #[arg(long)]
        push_secrets: bool,
    },
}

fn main() -> Result<()> {
    let cli = Cli::parse();
    let config = load_config(&cli.config)?;
    match cli.command {
        Cmd::Sync { push_secrets } => sync(&config, &cli.config, push_secrets),
    }
}

fn load_config(path: &Path) -> Result<Config> {
    let text = fs::read_to_string(path).with_context(|| {
        format!(
            "reading {} (copy config.example.toml to get started)",
            path.display()
        )
    })?;
    Config::from_toml(&text).with_context(|| format!("parsing {}", path.display()))
}

fn sync(config: &Config, config_path: &Path, push_secrets: bool) -> Result<()> {
    // Generated files go next to the config so `--config` works from any directory.
    let root = config_path.parent().unwrap_or(Path::new("."));

    let wrangler = root.join("wrangler.toml");
    fs::write(&wrangler, wrangler_toml(config)?)
        .with_context(|| format!("writing {}", wrangler.display()))?;
    println!("wrote {}", wrangler.display());

    let dev_vars = root.join(".dev.vars");
    write_private(&dev_vars, &dev_vars_file(config)?)?;
    println!("wrote {} (local secrets for `wrangler dev`)", dev_vars.display());

    if push_secrets {
        push(config, root)?;
    }
    Ok(())
}

fn wrangler_toml(config: &Config) -> Result<String> {
    use toml::{Table, Value};

    let tz = &config.location.timezone;
    ensure!(
        !tz.is_empty()
            && tz
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || "/_+-".contains(c)),
        "location.timezone {tz:?} is not an IANA zone name"
    );

    let mut doc = Table::new();
    doc.insert("name".into(), config.worker.name.clone().into());
    doc.insert(
        "main".into(),
        format!("{WORKER_DIR}/build/index.js").into(),
    );
    doc.insert("compatibility_date".into(), COMPATIBILITY_DATE.into());

    if let Some(domain) = &config.worker.domain {
        let mut route = Table::new();
        route.insert("pattern".into(), domain.clone().into());
        route.insert("custom_domain".into(), true.into());
        doc.insert("routes".into(), Value::Array(vec![route.into()]));
    }

    let mut build = Table::new();
    // Only compile the configured zone into chrono-tz to keep the wasm small.
    build.insert(
        "command".into(),
        format!(
            "cargo install -q worker-build@^0.8 && \
             CHRONO_TZ_TIMEZONE_FILTER='{tz}' worker-build --release"
        )
        .into(),
    );
    build.insert("cwd".into(), WORKER_DIR.into());
    build.insert(
        "watch_dir".into(),
        Value::Array(vec![
            format!("{WORKER_DIR}/src").into(),
            "crates/core/src".into(),
        ]),
    );
    doc.insert("build".into(), build.into());

    let vars: Table = config
        .vars()
        .into_iter()
        .map(|(k, v)| (k.to_string(), v.into()))
        .collect();
    doc.insert("vars".into(), vars.into());

    let mut triggers = Table::new();
    triggers.insert("crons".into(), Value::Array(vec![CRON.into()]));
    doc.insert("triggers".into(), triggers.into());

    if let Some(id) = &config.worker.kv_namespace_id {
        let mut kv = Table::new();
        kv.insert("binding".into(), KV_BINDING.into());
        kv.insert("id".into(), id.clone().into());
        doc.insert("kv_namespaces".into(), Value::Array(vec![kv.into()]));
    }

    Ok(format!(
        "# Generated by `pulse sync` from config.toml. Do not edit; do not commit.\n\n{}",
        toml::to_string(&doc)?
    ))
}

fn dev_vars_file(config: &Config) -> Result<String> {
    let mut out = String::from("# Generated by `pulse sync`. Do not commit.\n");
    for (key, value) in config.secrets.bindings() {
        if value.contains(['"', '\\', '\n', '\r']) {
            bail!("secret {key} contains a quote, backslash or newline");
        }
        out.push_str(&format!("{key}=\"{value}\"\n"));
    }
    Ok(out)
}

/// Write a file readable only by the owner, since it holds secrets.
fn write_private(path: &Path, contents: &str) -> Result<()> {
    let mut opts = fs::OpenOptions::new();
    opts.write(true).create(true).truncate(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::{OpenOptionsExt, PermissionsExt};
        opts.mode(0o600);
        // `mode` only applies on create; tighten an existing file too.
        if path.exists() {
            fs::set_permissions(path, fs::Permissions::from_mode(0o600))?;
        }
    }
    opts.open(path)
        .and_then(|mut f| f.write_all(contents.as_bytes()))
        .with_context(|| format!("writing {}", path.display()))
}

/// Upload secrets over stdin so they never touch disk outside config.toml.
fn push(config: &Config, root: &Path) -> Result<()> {
    let secrets: serde_json::Map<String, serde_json::Value> = config
        .secrets
        .bindings()
        .into_iter()
        .map(|(k, v)| (k.to_string(), v.into()))
        .collect();
    if secrets.is_empty() {
        println!("no secrets set in [secrets], nothing to push");
        return Ok(());
    }

    let mut child = Command::new("npx")
        .args(["wrangler", "secret", "bulk"])
        .current_dir(root)
        .stdin(Stdio::piped())
        .spawn()
        .context("running `npx wrangler secret bulk` (did you `npm install`?)")?;
    child
        .stdin
        .take()
        .expect("stdin is piped")
        .write_all(serde_json::to_string(&secrets)?.as_bytes())?;
    let status = child.wait()?;
    ensure!(status.success(), "wrangler secret bulk failed: {status}");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn example() -> Config {
        Config::from_toml(include_str!("../../../config.example.toml")).unwrap()
    }

    #[test]
    fn wrangler_toml_has_no_secrets_and_parses() {
        let mut cfg = example();
        cfg.secrets.github_token = "ghp_secret".into();
        cfg.worker.domain = Some("pulse.example.com".into());
        cfg.worker.kv_namespace_id = Some("abc123".into());

        let out = wrangler_toml(&cfg).unwrap();
        assert!(!out.contains("ghp_secret"));

        let parsed: toml::Table = toml::from_str(&out).unwrap();
        assert_eq!(parsed["routes"][0]["pattern"].as_str(), Some("pulse.example.com"));
        assert_eq!(parsed["kv_namespaces"][0]["binding"].as_str(), Some("PULSE"));
        assert_eq!(parsed["vars"]["TIMEZONE"].as_str(), Some("Europe/Helsinki"));
    }

    #[test]
    fn rejects_shell_metacharacters_in_timezone() {
        let mut cfg = example();
        cfg.location.timezone = "UTC'; rm -rf ~; '".into();
        assert!(wrangler_toml(&cfg).is_err());
    }
}
